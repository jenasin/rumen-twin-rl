def ensure_dirs() -> None:
    for key, p in PATHS.items():
        if key in ("config", "seeds"):
            continue
        p.mkdir(parents=True, exist_ok=True)


_CONFIG_CACHE: Dict[str, Any] = {}


def load_config(path: Optional[os.PathLike] = None, refresh: bool = False) -> Dict[str, Any]:
    """Load config.yaml (cached)."""
    p = Path(path) if path is not None else PATHS["config"]
    key = str(p)
    if refresh or key not in _CONFIG_CACHE:
        with open(p, "r") as fh:
            _CONFIG_CACHE[key] = yaml.safe_load(fh)
    return _CONFIG_CACHE[key]


def load_seeds(path: Optional[os.PathLike] = None) -> Dict[str, Any]:
    p = Path(path) if path is not None else PATHS["seeds"]
    with open(p, "r") as fh:
        return yaml.safe_load(fh)


def deep_update(base: Dict[str, Any], overrides: Dict[str, Any]) -> Dict[str, Any]:
    """Recursively merge ``overrides`` into a deep copy of ``base``."""
    import copy

    out = copy.deepcopy(base)
    for k, v in (overrides or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_update(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


# --------------------------------------------------------------------------
# Deterministic seeding
# --------------------------------------------------------------------------
def stable_hash(*parts: Any) -> int:
    """Deterministic 32-bit hash of the string form of ``parts``.

    ``hash()`` is randomised per process in Python, so we use blake2b to make
    episode seeds reproducible across runs and machines.
    """
    payload = "|".join(str(p) for p in parts).encode("utf-8")
    digest = hashlib.blake2b(payload, digest_size=4).digest()
    return int.from_bytes(digest, "big")


def episode_seed(offset: int, *parts: Any) -> int:
    return int((offset + stable_hash(*parts)) % (2**31 - 1))


def make_rng(seed: int) -> np.random.Generator:
    return np.random.default_rng(int(seed) % (2**32 - 1))


