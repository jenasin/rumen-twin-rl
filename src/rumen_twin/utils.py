def write_parquet_or_csv(df, path_no_ext: Path) -> Path:
    """Write Parquet when pyarrow is available, otherwise CSV."""
    path_no_ext = Path(path_no_ext)
    path_no_ext.parent.mkdir(parents=True, exist_ok=True)
    try:
        import pyarrow  # noqa: F401

        p = path_no_ext.with_suffix(".parquet")
        df.to_parquet(p, index=False)
        return p
    except Exception:
        p = path_no_ext.with_suffix(".csv")
        df.to_csv(p, index=False)
        return p


def read_table(path_no_ext: Path):
    """Read a table written by :func:`write_parquet_or_csv`."""
    import pandas as pd

    path_no_ext = Path(path_no_ext)
    pq = path_no_ext.with_suffix(".parquet")
    csv = path_no_ext.with_suffix(".csv")
    if pq.exists():
        return pd.read_parquet(pq)
    if csv.exists():
        return pd.read_csv(csv)
    raise FileNotFoundError(f"Neither {pq} nor {csv} exists. Run the experiments first.")


def save_json(obj: Any, path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    def _default(o):
        if isinstance(o, (np.integer,)):
            return int(o)
        if isinstance(o, (np.floating,)):
            return float(o)
        if isinstance(o, np.ndarray):
            return o.tolist()
        if isinstance(o, Path):
            return str(o)
        return str(o)

    with open(path, "w") as fh:
        json.dump(obj, fh, indent=2, default=_default)


def banner(text: str, width: int = 74) -> str:
    line = "=" * width
    return f"\n{line}\n{text}\n{line}"
