# Small math helpers
# --------------------------------------------------------------------------
def clip(x: float, lo: float, hi: float) -> float:
    return lo if x < lo else (hi if x > hi else x)


def relu(x: float) -> float:
    return x if x > 0.0 else 0.0


def gaussian_kernel(x: float, mu: float, sigma: float) -> float:
    z = (x - mu) / sigma
    return float(np.exp(-0.5 * z * z))


def truncated_normal(rng: np.random.Generator, mean: float, sd: float,
                     lo: float, hi: float, size: Optional[int] = None):
    """Draw from N(mean, sd) and clip to [lo, hi] (rejection-free, clipped)."""
    x = rng.normal(mean, sd, size=size)
    return np.clip(x, lo, hi)


def halflife_to_decay(halflife_hours: float, dt_minutes: float) -> float:
    """Per-step multiplicative decay factor for a given half-life."""
    steps_per_halflife = (halflife_hours * 60.0) / dt_minutes
    return float(0.5 ** (1.0 / steps_per_halflife))


def safe_float(x) -> float:
    v = float(x)
    if not np.isfinite(v):
        raise FloatingPointError(f"Non-finite value encountered: {x}")
    return v


